import { limpiarAus, agregarAus, quitarAus, ausenciasDeMes, migrarVac, reporte, reporteCsv, diasEntre, esFecha } from '../src/lib/ausencias.js';
import { normalizarPersonal } from '../src/lib/personal.js';
import { paraGuardar, mezclarPersonal } from '../src/lib/personalNube.js';
let fallas = 0;
const ok = (c, m) => {
  console.log((c ? 'ok - ' : 'FALLA - ') + m);
  if (!c) fallas++;
};
let lista = normalizarPersonal([]);
ok(esFecha('2026-02-28') && !esFecha('2026-02-30') && !esFecha('26-1-1'), 'fechas válidas e inválidas');
ok(diasEntre('2026-11-30', '2026-12-02') === 3 && diasEntre('2026-12-05', '2026-12-05') === 1, 'días calendario inclusivos');
lista = agregarAus(lista, 'mayra', { t: 'vac', de: '2026-12-14', a: '2026-12-18' });
lista = agregarAus(lista, 'mayra', { t: 'vac', de: '2026-12-14', a: '2026-12-18' });
ok(lista.find((p) => p.id === 'mayra').aus.length === 1, 'la misma ausencia no se duplica');
lista = agregarAus(lista, 'wendy', { t: 'lic', de: '2026-11-20', a: '2027-02-10', n: 'Maternidad' });
lista = agregarAus(lista, 'wendy', { t: 'raro', de: '2027-03-01', a: '2027-03-01' });
ok(lista.find((p) => p.id === 'wendy').aus[1].t === 'otro', 'un motivo desconocido pasa a "otro"');
lista = agregarAus(lista, 'wendy', { t: 'med', de: '2026-12-10', a: '2026-12-05' });
ok(lista.find((p) => p.id === 'wendy').aus.length === 2, 'una fecha final antes de la inicial se ignora');
lista = agregarAus(lista, 'noexiste', { t: 'vac', de: '2026-12-01', a: '2026-12-01' });
ok(!lista.some((p) => p.id === 'noexiste'), 'persona que no existe no se crea');
const nov = ausenciasDeMes(lista, '2026-11');
const dic = ausenciasDeMes(lista, '2026-12');
const feb = ausenciasDeMes(lista, '2027-02');
const mar = ausenciasDeMes(lista, '2027-03');
ok(nov.length === 1 && nov[0].id === 'wendy' && nov[0].de === 20 && nov[0].a === 30 && nov[0].t === 'lic', 'licencia larga: noviembre del 20 al 30');
ok(dic.some((v) => v.id === 'wendy' && v.de === 1 && v.a === 31) && dic.some((v) => v.id === 'mayra' && v.de === 14 && v.a === 18), 'diciembre: Wendy todo el mes y Mayra del 14 al 18');
ok(feb.length === 1 && feb[0].de === 1 && feb[0].a === 10, 'febrero: hasta el 10');
ok(mar.length === 1 && mar[0].id === 'wendy' && mar[0].t === 'otro', 'marzo: solo la ausencia de un día');
ok(ausenciasDeMes(lista, '2027-04').length === 0, 'abril: nadie');
const r = reporte(lista, 2026, null);
const w = r.filas.find((f) => f.id === 'wendy');
ok(w.lic === 42 && w.dias === 42, 'año 2026: Wendy 42 días de licencia (20 nov al 31 dic) → ' + w.lic);
ok(r.filas.find((f) => f.id === 'mayra').vac === 5, 'Mayra 5 días de vacaciones');
ok(r.total.vac === 5 && r.total.lic === 42 && r.total.dias === 47, 'totales del año');
const rm = reporte(lista, 2026, 11);
ok(rm.filas.find((f) => f.id === 'wendy').lic === 31 && rm.total.dias === 36, 'diciembre: 31 + 5');
const r27 = reporte(lista, 2027, null);
ok(r27.filas.find((f) => f.id === 'wendy').lic === 41 && r27.filas.find((f) => f.id === 'wendy').otro === 1, 'año 2027: 41 días (1 ene al 10 feb) y 1 de otro → ' + r27.filas.find((f) => f.id === 'wendy').lic);
ok(w.detalle[0].completa.a === '2027-02-10' && w.detalle[0].a === '2026-12-31', 'el detalle recorta al periodo pero recuerda la ausencia completa');
ok(reporte(lista, 2026, 5).total.dias === 0, 'junio: sin ausencias');
const csv = reporteCsv(r, 'Prueba');
ok(csv.startsWith('﻿') && csv.includes('Wendy;0;0;0;42;0;42;1') && csv.includes('Maternidad'), 'el Excel (CSV) trae la tabla y el detalle');
let q = quitarAus(lista, 'wendy', lista.find((p) => p.id === 'wendy').aus[0]);
ok(q.find((p) => p.id === 'wendy').aus.length === 1, 'quitar una ausencia');
const m = migrarVac(normalizarPersonal([]), '2026-12', [{ id: 'mayra', de: 3, a: 5 }, { id: 'fantasma', de: 1, a: 1 }]);
ok(m.find((p) => p.id === 'mayra').aus[0].de === '2026-12-03' && m.find((p) => p.id === 'mayra').aus[0].t === 'vac' && !m.some((p) => p.id === 'fantasma'), 'las vacaciones viejas del horario pasan al registro como vacaciones');
ok(migrarVac(m, '2026-12', [{ id: 'mayra', de: 3, a: 5 }]) !== undefined && migrarVac(m, '2026-12', [{ id: 'mayra', de: 3, a: 5 }]).find((p) => p.id === 'mayra').aus.length === 1, 'migrar dos veces no duplica');
const guardada = paraGuardar(lista);
ok(guardada.find((p) => p.id === 'wendy').aus.length === 2 && !guardada.find((p) => p.id === 'tania').aus, 'al guardar en Google solo van las ausencias de quien las tiene');
const vuelta = normalizarPersonal(JSON.parse(JSON.stringify(guardada)));
ok(JSON.stringify(vuelta.find((p) => p.id === 'wendy').aus) === JSON.stringify(lista.find((p) => p.id === 'wendy').aus), 'ida y vuelta sin cambios');
const mezcla = mezclarPersonal(guardada, normalizarPersonal([]), false);
ok(mezcla.find((p) => p.id === 'wendy').aus.length === 2, 'al traer de Google llegan las ausencias');
const mezcla2 = mezclarPersonal(paraGuardar(normalizarPersonal([])), lista, false);
ok(mezcla2.find((p) => p.id === 'wendy').aus.length === 2, 'si Google aún no las tiene, no se pierden las de este navegador');
ok(limpiarAus('x').length === 0 && limpiarAus([null, {}, { de: 'a' }]).length === 0, 'basura se descarta');
process.exit(fallas ? 1 : 0);

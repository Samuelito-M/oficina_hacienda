import { DOMParser, XMLSerializer } from '@xmldom/xmldom';
import JSZip from 'jszip';
import fs from 'fs';
import * as PDFLib from 'pdf-lib';
import fontkit from '@pdf-lib/fontkit';
globalThis.DOMParser = DOMParser; globalThis.XMLSerializer = XMLSerializer;
const { leerGrillaExcel, analizarHorarioExcel } = await import('../src/lib/horarioExcel.js');
const { normalizarPersonal } = await import('../src/lib/personal.js');
const A = await import('../src/lib/horarioApp.js');
const X = await import('../src/lib/horarioExport.js');
const J = (x) => JSON.stringify(x);
const ok = (c, m) => { console.log((c ? 'ok - ' : 'FALLA - ') + m); if (!c) process.exitCode = 1; };
const [, , xlsx, out] = process.argv;
const personal = normalizarPersonal([]);
const an = analizarHorarioExcel(await leerGrillaExcel(fs.readFileSync(xlsx), JSZip), personal, 'HORARIO.xlsx');
ok((an.feriados || []).join() === '2,3,20', 'lee los feriados del Excel: ' + an.feriados);
let { horario: nov, config, agregados } = A.desdeExcel(an.dias, personal, A.configInicial());
nov.fer = an.feriados;
ok(Object.keys(nov.dias).length >= 28 && !agregados.length, `noviembre importado: ${Object.keys(nov.dias).length} días, sin gente desconocida`);
ok(A.en(nov, 7, 'Casa 1').join() === 'miguel,patricia', 'sábado 7 Casa 1 = Miguel y Paty');
ok(J(config) === J(A.configInicial()), 'subir el Excel no cambia las reglas ni el personal');
ok(J(nov).length < 45000 && J(config).length < 45000, `todo cabe en una celda (horario ${J(nov).length}, personal ${J(config).length} caracteres)`);
ok(J(A.normalizarHorario(JSON.parse(J(nov)))) === J(A.normalizarHorario(nov)), 'normalizar es estable');
const cn = A.contexto('2026-11', nov, config);
ok(!A.problemas(cn).some((p) => p.tipo === 'fuera'), 'Yvelice y Coro en noviembre no dan aviso (trabajaron hasta noviembre)');
ok(cn.nombre('yvelice') === 'Yvelice', 'sus nombres siguen saliendo bien');
const xl = await X.generarExcelHorario('2026-11', nov, config, JSZip);
const an2 = analizarHorarioExcel(await leerGrillaExcel(xl, JSZip), personal, 'x.xlsx');
const firma = (a) => a.findes.map((f) => Object.entries(f.casas).map(([c, ids]) => c + ':' + [...ids].sort().join(',')).join(';')).join(' / ');
ok(an2.mes === 10 && firma(an) === firma(an2), 'el Excel generado da los mismos fines de semana que el original');
ok(firma(an) === firma(A.aAnalisis('2026-11', nov, config, personal)), 'Acuerdos lee igual desde la app que desde el Excel');
const { horario: dic, quitados } = A.copiarAnterior('2026-12', nov, config, { dias: {}, vac: [{ id: 'yazmira', de: 8, a: 12 }], fer: [25] });
const res = A.resumirQuitados(quitados, (x) => x);
ok(!J(dic).includes('yvelice') && !J(dic).includes('coro') && res.some((t) => /yvelice.*ya no trabaja/.test(t)) && res.some((t) => /yazmira.*vacaciones/.test(t)), 'copiar a diciembre quita a Yvelice y Coro y a quien está de vacaciones');
ok(A.en(dic, 5, 'Casa 1').join() === 'miguel,patricia' && !A.en(dic, 7, 'Casa 1').includes('miguel'), 'copia por semanas completas, sin el lunes feriado');
// armar diciembre siguiendo a noviembre real
const r = A.armar('2026-12', { dias: {}, vac: [], fer: [25] }, config, nov);
const cd = A.contexto('2026-12', r.horario, config);
const P = A.problemas(cd);
const ultimo = (id) => [27, 28, 29].some((d) => cn.donde(id, d));
const padres = config.personal.filter((p) => p.rol === 'padre');
ok(padres.every((p) => ultimo(p.id) !== cd.findes[0].dias.some((d) => cd.donde(p.id, d))), 'diciembre: los padres que trabajaron el 27-29 de noviembre descansan el 4-6: ' + padres.map((p) => p.n + (ultimo(p.id) ? ' descansa' : ' trabaja')).join(', '));
ok(padres.every((p) => cd.findesDe(p.id) === 2), 'cada padre de casa 2 fines de semana');
ok(!P.some((p) => p.tipo !== 'falta'), 'sin choques ni reglas rotas');
console.log('   faltas en diciembre:', P.length, [...new Set(P.map((p) => p.k))].join(', '));
ok(A.en(r.horario, 1, 'On Call').join() === (ultimo('viviana') ? 'viviana' : '') && A.en(r.horario, 3, 'On Call').join() === A.en(r.horario, 1, 'On Call').join(), 'on call del 1 al 3 de diciembre porque Viviana ' + (ultimo('viviana') ? 'trabajó' : 'no trabajó') + ' el último fin de semana de noviembre');
ok(A.moverMes('2026-12', 1) === '2027-01' && A.moverMes('2027-01', -1) === '2026-12', 'cambio de año');
const recursos = { normal: fs.readFileSync('node_modules/@fontsource/dm-sans/files/dm-sans-latin-400-normal.woff'), bold: fs.readFileSync('node_modules/@fontsource/dm-sans/files/dm-sans-latin-700-normal.woff') };
fs.writeFileSync(out + '/Horario diciembre.pdf', await X.generarPdfHorario('2026-12', r.horario, config, PDFLib, fontkit, recursos));
const xd = await X.generarExcelHorario('2026-12', r.horario, config, JSZip);
fs.writeFileSync(out + '/Horario diciembre.xlsx', xd);
const an3 = analizarHorarioExcel(await leerGrillaExcel(xd, JSZip), personal, 'd.xlsx');
ok(firma(an3) === firma(A.aAnalisis('2026-12', r.horario, config, personal)) && an3.findes.length === 4, 'el Excel de diciembre armado por reglas se lee igual');

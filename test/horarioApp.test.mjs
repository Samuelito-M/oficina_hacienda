import { DOMParser, XMLSerializer } from '@xmldom/xmldom';
import JSZip from 'jszip';
import fs from 'fs';
import * as PDFLib from 'pdf-lib';
import fontkit from '@pdf-lib/fontkit';
globalThis.DOMParser = DOMParser; globalThis.XMLSerializer = XMLSerializer;
const { leerGrillaExcel, analizarHorarioExcel } = await import('../src/lib/horarioExcel.js');
const { normalizarPersonal } = await import('../src/lib/personal.js');
const A = await import('../src/lib/horarioApp.js');
const X = await import('../src/lib/horarioExport.js');
const ok = (c, m) => { console.log((c ? 'ok - ' : 'FALLA - ') + m); if (!c) process.exitCode = 1; };
const [, , xlsx, out] = process.argv;
const personal = normalizarPersonal([]);
const an = analizarHorarioExcel(await leerGrillaExcel(fs.readFileSync(xlsx), JSZip), personal, 'HORARIO.xlsx');
let { horario: nov, config, agregados } = A.desdeExcel(an.dias, personal, A.configInicial());
nov.fer = [2, 3];
ok(Object.keys(nov.dias).length >= 28, `noviembre importado: ${Object.keys(nov.dias).length} días, agregados: ${agregados.join(',') || 'nadie'}`);
ok(A.en(nov, 7, 'Casa 1').join() === 'miguel,patricia', 'sábado 7 Casa 1 = Miguel y Paty');
const sJ = JSON.stringify(nov).length; ok(sJ < 45000, `cabe en una celda (${sJ} caracteres)`);
ok(JSON.stringify(A.normalizarHorario(JSON.parse(JSON.stringify(nov)))) === JSON.stringify(A.normalizarHorario(nov)), 'normalizar es estable');
// ida y vuelta excel
const xl = await X.generarExcelHorario('2026-11', nov, config, JSZip);
fs.writeFileSync(out + '/Horario noviembre.xlsx', xl);
const an2 = analizarHorarioExcel(await leerGrillaExcel(xl, JSZip), personal, 'x.xlsx');
ok(an2.mes === 10 && an2.anio === 2026, 'la app lee su propio Excel: mes y año');
const firma = (a) => a.findes.map((f) => Object.entries(f.casas).map(([c, ids]) => c + ':' + [...ids].sort().join(',')).join(';')).join(' / ');
ok(firma(an) === firma(an2), 'el Excel generado da los mismos fines de semana que el original');
const an3 = A.aAnalisis('2026-11', nov, config, personal);
ok(firma(an) === firma(an3), 'Acuerdos lee igual desde la app que desde el Excel');
// diciembre
const dic0 = { dias: {}, vac: [{ id: 'yazmira', de: 8, a: 12 }], fer: [25] };
const { horario: dic, quitados } = A.copiarAnterior('2026-12', nov, config, dic0);
ok(A.en(dic, 5, 'Casa 1').join() === 'miguel,patricia', 'sábado 5 dic copia el 1er sábado de nov');
ok(!A.en(dic, 7, 'Casa 1').includes('miguel'), 'lunes 7 dic no copia el feriado del 2 de nov');
ok(quitados.every((q) => q.id === 'yazmira') && quitados.length > 0, 'quita a Yazmira por vacaciones: ' + A.resumirQuitados(quitados, (x) => x).join('; '));
let ctx = A.contexto('2026-12', dic, config);
const antes = A.problemas(ctx).filter((p) => p.tipo === 'falta').length;
config.personal.find((p) => p.id === 'tania').oc = true; config.personal.find((p) => p.id === 'wendy').oc = true;
const comp = A.completar('2026-12', dic, config);
ctx = A.contexto('2026-12', comp.horario, config);
const prob = A.problemas(ctx);
ok(prob.filter((p) => p.tipo === 'falta').length < antes, `completar reduce faltas: ${antes} → ${prob.filter((p) => p.tipo === 'falta').length} (casas ${comp.casas}, on call ${comp.calls})`);
ok(!prob.some((p) => p.tipo === 'doble' || p.tipo === 'vac'), 'completar no crea choques ni usa gente de vacaciones');
ok(comp.calls === 31 && A.en(comp.horario, 25, 'On Call').length === 1, 'on call todos los días');
ok(A.completar('2026-12', comp.horario, config).nuevos.length === 0, 'completar dos veces no agrega nada más');
const sin = A.quitarPersona(comp.horario, 'wendy');
ok(!JSON.stringify(sin).includes('wendy'), 'quitar persona la saca de todo el mes');
ok(A.moverMes('2026-12', 1) === '2027-01' && A.moverMes('2027-01', -1) === '2026-12', 'cambio de año');
const ene = A.copiarAnterior('2027-01', comp.horario, config, null).horario;
ok(Object.keys(ene.dias).length === 31, 'enero 2027 se copia de diciembre');
const recursos = { normal: fs.readFileSync('node_modules/@fontsource/dm-sans/files/dm-sans-latin-400-normal.woff'), bold: fs.readFileSync('node_modules/@fontsource/dm-sans/files/dm-sans-latin-700-normal.woff') };
fs.writeFileSync(out + '/Horario diciembre.pdf', await X.generarPdfHorario('2026-12', comp.horario, config, PDFLib, fontkit, recursos));
fs.writeFileSync(out + '/Horario diciembre.xlsx', await X.generarExcelHorario('2026-12', comp.horario, config, JSZip));
const r = A.resumenMes(ctx); console.log('   resumen:', r.slice(0, 5).map((x) => `${x.p.n} ${x.dias}`).join(', '));

const { iniciar } = require('./arnes.cjs');
(async () => {
  const { p, ok, fila, entrar, irA, preguntar, cerrar } = await iniciar({ hash: '#horario' });
  await entrar();
  await p.waitForSelector('#h-mes');
  await irA('Noviembre 2026');
  await p.waitForSelector('#h-armar');
  await p.click('#h-armar');
  await p.waitForSelector('.h-barra');
  await p.click('#h-guardar');
  await p.waitForTimeout(800);
  await irA('Diciembre 2026');
  await p.waitForSelector('#h-armar');
  let r = await preguntar('arma el horario de diciembre');
  ok(/Armé diciembre|Armé Diciembre/i.test(r), 'Sam Jr. arma el horario: ' + r.slice(0, 120));
  await p.waitForSelector('.h-barra');
  r = await preguntar('guarda el horario');
  ok(/Guardado/.test(r), 'Sam Jr. guarda: ' + r.slice(0, 60));
  const g = fila('2026-12');
  ok(g && Object.keys(g.dias).length > 25, 'quedó guardado en Google');
  const diasWendy = Object.entries(g.dias).filter(([, v]) => Object.entries(v).some(([k, l]) => k !== 'On Call' && l.includes('wendy'))).map(([d]) => +d);
  r = await preguntar('pon a Wendy AM todos los días que le toca');
  ok(new RegExp(`Puse AM a Wendy en ${diasWendy.length} días`).test(r), 'AM a Wendy en todos sus días: ' + r.slice(0, 100));
  await p.click('#h-ver-mes').catch(() => {});
  await p.waitForTimeout(300);
  const conAm = await p.$$eval('[data-k] .tur.am', (l) => l.length);
  ok(conAm === diasWendy.length, `en pantalla salen ${conAm} etiquetas AM`);
  // deshacer desde el botón
  await p.click('#asistente .as-bot:last-of-type button:has-text("Deshacer")');
  await p.waitForTimeout(600);
  ok((await p.$$eval('[data-k] .tur.am', (l) => l.length)) === 0, 'Deshacer quita los AM');
  r = await preguntar('pon a Wendy AM todos los días que le toca');
  await p.click('#asistente .as-bot:last-of-type button:has-text("Guardar")');
  await p.waitForTimeout(1000);
  const g2 = fila('2026-12');
  ok(diasWendy.every((d) => Object.values(g2.tur[d] || {}).some((m) => m.wendy === 'am')), 'con “Guardar” queda guardado el AM');
  // quitar a alguien un día
  const dM = Object.entries(g2.dias).find(([d, v]) => +d > 3 && Object.entries(v).some(([k, l]) => k !== 'On Call' && l.includes('mayra')))[0];
  r = await preguntar(`quita a Mayra del ${dM}`);
  ok(/Quité a Mayra/.test(r), 'quitar a Mayra: ' + r.slice(0, 80));
  ok(!(await p.textContent(`[data-d="${dM}"]`)).includes('Mayra') || !(await p.$$eval(`[data-d="${dM}"][data-k]`, (l) => l.some((e) => e.textContent.includes('Mayra')))), `Mayra ya no sale el ${dM}`);
  r = await preguntar('pon a Jauna de on call el 22');
  ok(/Puse a Jauna de on call/.test(r), 'on call a mano por chat');
  r = await preguntar('marca el 25 como feriado');
  ok(/feriado/.test(r), 'feriado por chat');
  r = await preguntar('pon una nota el 24: cena de Navidad');
  ok(/cena de Navidad/.test(r), 'nota por chat');
  r = await preguntar('guarda');
  const g3 = fila('2026-12');
  ok(g3.fer.includes(25) && g3.notas[24] === 'cena de Navidad' && g3.dias[22]['On Call'].join() === 'x:Jauna' && !Object.values(g3.dias[dM]).some((l) => l.includes('mayra')), 'todo quedó guardado (feriado, nota, on call, Mayra quitada)');
  r = await preguntar('Mayra está de vacaciones del 28 al 30');
  ok(/ausencia de \*?\*?Mayra|ausencia de Mayra/.test(r) && /¿Lo hago\?/.test(r), 'ausencia pide confirmación');
  await p.click('#asistente .as-bot:last-of-type button:has-text("Sí, hazlo")');
  await p.waitForTimeout(800);
  const txt = await p.$$eval('#asistente .as-bot', (l) => l[l.length - 1].textContent);
  ok(/Anoté la ausencia/.test(txt), 'anotada: ' + txt.slice(0, 80));
  ok(!(await p.$$eval('[data-d="29"][data-k]', (l) => l.some((e) => e.textContent.includes('Mayra')))), 'Mayra no sale el 29');
  r = await preguntar('guarda');
  await p.click('#tab-inicio');
  await p.waitForTimeout(500);
  r = await preguntar('arma el horario de enero');
  ok(/Armé enero/i.test(r), 'desde Inicio, armar enero cambia de mes y lo arma: ' + r.slice(0, 60));
  ok(/#horario$/.test(p.url()) && /Enero 2027/.test(await p.textContent('#h-mes')), 'abrió Horario en enero');
  r = await preguntar('pon a Wendy PM los sábados de enero');
  ok(/Puse PM a Wendy/.test(r), 'PM los sábados de enero: ' + r.slice(0, 80));
  r = await preguntar('pon a Wendy PM el 1 de diciembre');
  ok(/cambios sin guardar/.test(r), 'si hay cambios sin guardar en otro mes, avisa: ' + r.slice(0, 80));
  r = await preguntar('¿quién trabaja el 15 de diciembre?');
  ok(/Casa/.test(r) && !/Puse|Quité/.test(r), 'las preguntas siguen siendo preguntas');
  await cerrar();
})();

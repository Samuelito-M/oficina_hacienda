const { iniciar } = require('./arnes.cjs');
(async () => {
  const { p, ok, fila, entrar, irA, cerrar, S } = await iniciar({ hash: '#horario' });
  await entrar();
  await p.waitForSelector('#h-mes');
  await irA('Noviembre 2026');
  await p.waitForSelector('#h-armar');
  await p.click('#h-armar');
  await p.waitForSelector('.h-barra');
  await p.click('#h-guardar');
  await p.waitForTimeout(800);
  await irA('Diciembre 2026');
  await p.waitForSelector('#h-armar');
  await p.click('#h-armar');
  await p.waitForSelector('.h-barra');
  await p.click('#h-guardar');
  await p.waitForTimeout(800);
  const dic = fila('2026-12');
  const nov = fila('2026-11');
  const vierneDe = (d) => { const w = new Date(2026, 11, d).getDay(); return d - ((w + 2) % 7); };
  const esperado = (d) => { const v = vierneDe(d); const trabaja = v >= 1 ? Object.entries(dic.dias[v] || {}).some(([k, l]) => k !== 'On Call' && l.includes('viviana')) : Object.entries(nov.dias[30 + v] || {}).some(([k, l]) => k !== 'On Call' && l.includes('viviana')); return trabaja ? 'viviana' : 'x:Jauna'; };
  const mal = [];
  for (let d = 1; d <= 31; d++) if ((dic.dias[d]['On Call'] || []).join() !== esperado(d)) mal.push(`${d}:${(dic.dias[d]['On Call'] || []).join()}≠${esperado(d)}`);
  ok(!mal.length, 'todos los días de diciembre tienen su on call según la regla' + (mal.length ? ' — ' + mal.join(' ') : ''));
  // poner a mano a Tania de on call el martes 15
  await p.click('#h-ver-mes');
  await p.waitForTimeout(300);
  await p.click('[data-d="15"][data-k="On Call"]');
  await p.waitForSelector('#h-elegir-ok');
  ok(/si Viviana trabaja el viernes/.test(await p.textContent('dialog[open]')), 'la ventana del on call explica la regla');
  if (await p.isChecked('#h-todo-bloque').catch(() => false)) await p.uncheck('#h-todo-bloque');
  for (const el of await p.$$('dialog[open] .h-opc input:checked')) await el.click();
  await p.click('dialog[open] #h-otro');
  await p.fill('#h-otro-nombre', 'Tania Prueba');
  await p.click('#h-otro-ok');
  await p.click('#h-elegir-ok');
  await p.waitForTimeout(200);
  // cambiar una casa del fin de semana (antes esto borraba los on call puestos a mano)
  await p.click('[data-d="12"][data-k="Casa 2"]');
  await p.waitForSelector('#h-elegir-ok');
  await p.click('#h-elegir-ok');
  await p.waitForTimeout(200);
  await p.click('#h-guardar');
  await p.waitForTimeout(800);
  ok((fila('2026-12').dias[15]['On Call'] || []).join() === 'x:Tania Prueba', 'el on call puesto a mano se guarda y no se borra al cambiar otras casas');
  await p.reload();
  await entrar().catch(() => {});
  await p.waitForSelector('#h-mes');
  await irA('Diciembre 2026');
  await p.waitForSelector('.h-barra');
  await p.click('#h-ver-mes');
  await p.waitForTimeout(400);
  ok(/Tania Prueba/.test(await p.textContent('[data-d="15"][data-k="On Call"]')), 'al volver a entrar sigue ahí');
  ok(!(await p.$('#h-guardar:not([disabled])')) || !(await p.isVisible('.h-sucio').catch(() => false)), 'entrar no deja cambios pendientes');
  // volver a lo automático
  await p.click('[data-d="15"][data-k="On Call"]');
  await p.waitForSelector('#h-oc-auto');
  await p.click('#h-oc-auto');
  await p.waitForTimeout(200);
  ok((await p.textContent('[data-d="15"][data-k="On Call"]')).includes(esperado(15) === 'viviana' ? 'Viviana' : 'Jauna'), '“Volver a lo automático” pone otra vez la regla');
  await cerrar();
})();

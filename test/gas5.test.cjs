const crear = require('./gasSim.cjs');
const ok = (c, m) => { console.log((c ? 'ok - ' : 'FALLA - ') + m); if (!c) process.exitCode = 1; };
const S = crear(__dirname + '/../google/Code.gs'); S.props.CLAVE = 'K';
const tk = S.call({ accion: 'entrar', clave: 'K' }).token;
const C = (d) => S.call({ ...d, token: tk });
const ana = C({ accion: 'guardar', nino: { nombre: 'Ana', casa: 'Casa 3' } }).nino;
const luis = C({ accion: 'guardar', nino: { nombre: 'Luis', casa: 'Casa 1' } }).nino;
const b64 = (t) => Buffer.from(t).toString('base64');
let r = C({ accion: 'albumEstado' });
ok(r.ok && r.version === 7 && r.carpeta === null && r.cuentas._total === 0, 'al principio no hay carpeta elegida');
r = C({ accion: 'albumSubir', foto: b64('x'), mini: b64('m'), ninos: [ana.id] });
ok(!r.ok && r.error === 'sinCarpeta', 'sin carpeta no deja subir y lo explica');
ok(C({ accion: 'albumCarpeta', enlace: 'https://www.google.com' }).error === 'enlace', 'enlace que no es de carpeta');
const soloLectura = S.drive.crearCarpeta('Ajena', { soloLectura: true });
r = C({ accion: 'albumCarpeta', enlace: `https://drive.google.com/drive/folders/${soloLectura}` });
ok(!r.ok && r.error === 'drive' && /denegado/.test(r.mensaje), 'carpeta sin permiso de editor: avisa');
const comp = S.drive.crearCarpeta('Fotos Hacienda (compartida)');
r = C({ accion: 'albumCarpeta', enlace: `https://drive.google.com/drive/folders/${comp}?usp=sharing` });
ok(r.ok && r.carpeta.nombre === 'Fotos Hacienda (compartida)', 'elige la carpeta compartida desde el enlace');
ok(S.drive.hijos(comp).every((x) => x.borrado), 'la carpeta de prueba se borra');
r = C({ accion: 'albumSubir', foto: b64('FOTO1'), mini: b64('MINI1'), ninos: [ana.id, luis.id, 'inventado'], fecha: '2026-11-15', nombre: 'IMG_001.JPG', huella: 'h1' });
ok(r.ok && r.foto.ninos.length === 2 && r.foto.fecha === '2026-11-15', 'sube foto de grupo (ignora ids que no existen)');
const nom = (id) => S.drive.ver(id) && S.drive.ver(id).n;
const carpetas = (padre) => S.drive.hijos(padre, 'carpeta').filter((x) => !x.borrado).map((x) => x.n).sort();
ok(carpetas(comp).join() === 'Casa 1,Casa 3,Miniaturas (no tocar),Todas las fotos', 'arma Casa 1, Casa 3, Todas las fotos y Miniaturas en la carpeta compartida: ' + carpetas(comp).join());
const casa3 = S.drive.hijos(comp, 'carpeta').find((x) => x.n === 'Casa 3');
const fAna = S.drive.hijos(casa3.id, 'carpeta').find((x) => x.n === 'Ana');
ok(fAna && S.drive.hijos(fAna.id, 'atajo').length === 1, 'en Casa 3 → Ana queda un acceso a la foto');
const todas = S.drive.hijos(comp, 'carpeta').find((x) => x.n === 'Todas las fotos');
const mesC = S.drive.hijos(todas.id, 'carpeta').find((x) => x.n === '2026-11');
ok(mesC && S.drive.hijos(mesC.id, 'archivo')[0].n === '2026-11-15 IMG_001.jpg', 'la foto real está una sola vez en Todas las fotos → 2026-11');
r = C({ accion: 'albumSubir', foto: b64('FOTO1'), mini: b64('MINI1'), ninos: [ana.id], huella: 'h1' });
ok(r.ok && r.repetida, 'la misma foto dos veces: avisa que ya estaba');
r = C({ accion: 'albumSubir', foto: b64('FOTO2'), mini: b64('MINI2'), ninos: [], fecha: '2026-10-02', huella: 'h2' });
const sin = S.drive.hijos(comp, 'carpeta').find((x) => x.n === 'Sin ordenar');
ok(r.ok && sin && S.drive.hijos(sin.id, 'atajo').length === 1, 'foto sin niños va a Sin ordenar');
const idSin = r.foto.id;
r = C({ accion: 'albumEstado' });
ok(r.cuentas._total === 2 && r.cuentas._sin === 1 && r.cuentas[ana.id] === 1, 'cuenta fotos por niño y sin ordenar');
r = C({ accion: 'album', nino: ana.id });
ok(r.fotos.length === 1 && C({ accion: 'album', sin: true }).fotos[0].id === idSin && C({ accion: 'album' }).fotos[0].fecha === '2026-11-15', 'lista por niño, sin ordenar y todas (más nuevas primero)');
r = C({ accion: 'albumMinis', ids: [idSin] });
ok(r.minis[idSin] === 'data:image/jpeg;base64,' + b64('MINI2'), 'trae las miniaturas');
ok(C({ accion: 'albumFoto', id: idSin }).datos.endsWith(b64('FOTO2')), 'trae la foto completa');
r = C({ accion: 'albumEtiquetar', id: idSin, ninos: [luis.id] });
ok(r.ok && S.drive.hijos(sin.id, 'atajo').every((x) => x.borrado), 'al asignarla a Luis sale de Sin ordenar');
const casa1 = S.drive.hijos(comp, 'carpeta').find((x) => x.n === 'Casa 1');
const fLuis = S.drive.hijos(casa1.id, 'carpeta').find((x) => x.n === 'Luis');
ok(S.drive.hijos(fLuis.id, 'atajo').filter((x) => !x.borrado).length === 2, 'Luis ahora tiene 2 fotos en su carpeta');
C({ accion: 'guardar', nino: { ...ana, casa: 'Casa 4', nombre: 'Ana María' } });
const casa4 = S.drive.hijos(comp, 'carpeta').find((x) => x.n === 'Casa 4');
ok(casa4 && S.drive.ver(fAna.id).padres[0] === casa4.id && nom(fAna.id) === 'Ana María', 'si Ana cambia de casa y de nombre, su carpeta se mueve a Casa 4 y se renombra');
const sigue = C({ accion: 'guardar', nino: { nombre: 'Pedro', casa: 'Casa 2' } });
ok(sigue.ok && !sigue.nino.avisoCarpeta, 'guardar un niño sin fotos no toca Drive');
r = C({ accion: 'albumBorrar', id: idSin });
ok(r.ok && C({ accion: 'albumEstado' }).cuentas._total === 1 && S.drive.hijos(fLuis.id, 'atajo').filter((x) => !x.borrado).length === 1, 'borrar una foto la quita del álbum y de las carpetas');
ok(C({ accion: 'albumFoto', id: 'nada' }).error === 'noExiste', 'foto que no existe');
ok(C({ accion: 'albumSubir', foto: 'no es base64 !!', mini: b64('m') }).error === 'foto', 'foto dañada');
const d = Array.from({ length: 128 }, (_, i) => Math.sin(i) / 3);
r = C({ accion: 'guardarCaras', nuevas: [{ nino: ana.id, d }, { nino: 'inventado', d }, { nino: luis.id, d: [1, 2] }] });
ok(r.guardadas === 1, 'guarda solo caras válidas de niños que existen');
for (let k = 0; k < 15; k++) C({ accion: 'guardarCaras', nuevas: [{ nino: ana.id, d }] });
r = C({ accion: 'caras' });
ok(r.caras[ana.id].length === 12 && r.caras[ana.id][0].length === 128, 'guarda máximo 12 caras por niño');
ok(C({ accion: 'albumEstado', token: 'x' }).error === undefined, 'sigue con sesión');
ok(S.call({ accion: 'album' }).error === 'sesion', 'sin clave no se ve el álbum');

import JSZip from 'jszip';
const { DOMParser, XMLSerializer } = await import('@xmldom/xmldom');
globalThis.DOMParser = DOMParser;
globalThis.XMLSerializer = XMLSerializer;
const A = await import('../src/lib/horarioApp.js');
const { generarExcelHorario } = await import('../src/lib/horarioExport.js');
const { leerCelda, construirTokenizador } = await import('../src/lib/horario.js');
const ok = (c, m) => { console.log((c ? 'ok - ' : 'FALLA - ') + m); if (!c) process.exitCode = 1; };
const cfg = A.configInicial();
let h = A.armar('2026-12', { dias: {}, vac: [], fer: [], notas: {}, obs: '' }, cfg, null).horario;
const a = A.en(h, 2, 'Casa 1')[0];
const b = cfg.personal.find((p) => p.id !== a && p.rol !== 'padre').id;
h = A.poner(h, 2, 'Casa 1', [a, b]);
ok(!!a && !!b, `día 2 Casa 1: ${a}, ${b}`);
h = A.ponerTurnos(h, 2, 'Casa 1', { [a]: 'am', [b]: 'pm', nadie: 'am', [a + 'x']: 'pm' });
ok(A.turnoDe(h, 2, 'Casa 1', a) === 'am' && A.turnoDe(h, 2, 'Casa 1', b) === 'pm', 'se guarda AM y PM por persona');
ok(!('nadie' in h.tur[2]['Casa 1']), 'solo para quien está ese día en esa casa');
ok(A.turnoDe(h, 3, 'Casa 1', a) === '' && A.turnoDe(h, 2, 'Casa 2', a) === '', 'es por día y por casa');
let h2 = A.poner(h, 2, 'Casa 1', [b]);
ok(!A.turnoDe(h2, 2, 'Casa 1', a) && A.turnoDe(h2, 2, 'Casa 1', b) === 'pm', 'si se quita a la persona, se quita su turno');
h2 = A.poner(h2, 2, 'Casa 1', []);
ok(!h2.tur, 'sin nadie, no queda nada guardado');
h2 = A.ponerTurnos(h, 2, 'Casa 1', {});
ok(!h2.tur, 'quitar los turnos deja el horario como antes (opcional)');
const n = A.normalizarHorario(JSON.parse(JSON.stringify({ ...h, tur: { ...h.tur, 40: { 'Casa 1': { [a]: 'am' } }, 5: { 'Casa 1': { [a]: 'noche' } }, 6: { 'On Call': { [a]: 'am' } } } })));
ok(n.tur[2]['Casa 1'][a] === 'am' && !n.tur[40] && !n.tur[5] && !n.tur[6], 'al leer de Google se limpian los turnos raros');
const n0 = A.normalizarHorario(JSON.parse(JSON.stringify(A.armar('2026-12', { dias: {}, vac: [], fer: [], notas: {}, obs: '' }, cfg, null).horario)));
ok(!('tur' in n0), 'un horario sin turnos queda igual que antes');
const sig = A.soloDias({ dias: {}, vac: [], fer: [], notas: {}, obs: '' }, h, [2]);
ok(A.turnoDe(sig, 2, 'Casa 1', a) === 'am', 'los días de continuación también guardan el turno');
ok(A.conTurno('Mayra', 'am') === 'Mayra (AM)' && A.conTurno('Mayra', '') === 'Mayra', 'texto con turno');

const bytes = await generarExcelHorario('2026-12', h, cfg, JSZip);
const z = await JSZip.loadAsync(bytes);
const xml = (await Promise.all(Object.keys(z.files).filter((f) => /\.xml$/.test(f)).map((f) => z.file(f).async('string')))).join(' ');
const na = cfg.personal.find((p) => p.id === a).n;
ok(xml.includes(`${na} (AM)`), `el Excel dice “${na} (AM)”`);
const tok = construirTokenizador(cfg.personal.map((p) => ({ id: p.id, alias: [p.n] })));
const r = leerCelda(`Casa 1: ${na} (AM)-${cfg.personal.find((p) => p.id === b).n} (PM)`, tok);
ok(JSON.stringify(r.casas['Casa 1']) === JSON.stringify([a, b]), 'Acuerdos sigue leyendo bien un horario con AM/PM: ' + JSON.stringify(r.casas));

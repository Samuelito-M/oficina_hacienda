const crear = require('./gasSim.cjs');
const S = crear(__dirname + '/../google/Code.gs');
S.props.CLAVE = 'K';
const ok = (c, m) => { console.log((c ? 'ok - ' : 'FALLA - ') + m); if (!c) process.exitCode = 1; };
const t = S.call({ accion: 'entrar', clave: 'K' }).token;
ok(S.call({ accion: 'horario', mes: '2026-12' }).error === 'sesion', 'horario pide clave');
let r = S.call({ accion: 'horario', mes: '2026-12', token: t });
ok(r.ok && r.version === 8 && r.datos.horario === null && r.datos.anterior === null && r.datos.config === null && r.datos.mesAnterior === '2026-11', 'mes vacío');
const nov = { dias: { 1: { 'Casa 1': ['miguel', 'patricia'] } }, vac: [], fer: [2, 3] };
ok(S.call({ accion: 'guardarHorario', mes: '2026-11', horario: nov, token: t }).ok, 'guardar noviembre');
ok(S.call({ accion: 'guardarConfig', config: { personal: [{ id: 'miguel', n: 'Miguel' }], nec: {} }, token: t }).ok, 'guardar config');
r = S.call({ accion: 'horario', mes: '2026-12', token: t }).datos;
ok(r.horario === null && r.anterior.dias[1]['Casa 1'][1] === 'patricia' && r.config.personal[0].n === 'Miguel' && r.meses.join() === '2026-11', 'diciembre ve noviembre como anterior y la config');
nov.fer = [2];
S.call({ accion: 'guardarHorario', mes: '2026-11', horario: nov, token: t });
r = S.call({ accion: 'horario', mes: '2026-11', token: t }).datos;
ok(r.horario.fer.length === 1 && r.actualizado, 'actualizar reemplaza, no duplica');
ok(S.sheets.Horarios.rows.length === 3, 'una fila por mes + config');
ok(S.call({ accion: 'horario', mes: '2027-01', token: t }).datos.mesAnterior === '2026-12', 'enero mira a diciembre');
ok(!S.call({ accion: 'guardarHorario', mes: '2026-13', horario: nov, token: t }).ok, 'mes inválido se rechaza');
ok(!S.call({ accion: 'guardarHorario', mes: '2026-12', horario: 'x', token: t }).ok, 'horario inválido se rechaza');
ok(!S.call({ accion: 'guardarHorario', mes: '2026-12', horario: { x: 'a'.repeat(50000) }, token: t }).ok, 'horario gigante se rechaza');
S.call({ accion: 'guardarHorario', mes: '2026-12', horario: nov, token: t });
const ms = S.call({ accion: 'horarios', token: t }).meses;
ok(ms.length === 2 && ms[0].mes === '2026-12', 'lista de meses, el más nuevo primero');
ok(S.call({ accion: 'listar', token: t }).version === 8, 'niños sigue funcionando');
S.call({ accion: 'guardarHorario', mes: '2027-02', horario: { dias: {}, vac: [], fer: [], notas: {}, obs: '' }, token: t });
ok(!S.call({ accion: 'horarios', token: t }).meses.some((m) => m.mes === '2027-02'), 'un mes borrado no sale en la lista de Acuerdos');

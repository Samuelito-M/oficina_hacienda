ok(by(per, 'viviana').hasta === '2026-12', 'quitar en Horario pone hasta qué mes trabajó');
ok(P.trabajaEn(by(per, 'viviana'), '2026-12') && !P.trabajaEn(by(per, 'viviana'), '2027-01'), 'trabaja en diciembre, no en enero');
const v = { ...by(per, 'viviana'), completo: 'X Y', cedula: '1712345678' };
const fD = { sabado: new Date(2026, 11, 12) }, fE = { sabado: new Date(2027, 0, 9) };

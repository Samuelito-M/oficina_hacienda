ok(by(per, 'rosa') && !by(per, 'rosa').fijo && by(per, 'rosa').casa === '', 'auxiliar nueva aparece sola, no fija');
ok(by(per, 'pedro').fijo && by(per, 'pedro').casa === 'Casa 4', 'padre nuevo aparece fijo y en su casa');

const P = await import('../src/lib/personal.js');
const H = await import('../src/lib/horarioApp.js');
const S = await import('../src/lib/seleccion.js');
const ok = (c, m) => { console.log((c ? 'ok - ' : 'FALLA - ') + m); if (!c) process.exitCode = 1; };
const per0 = P.normalizarPersonal([]);
let cfg = H.configInicial();
let per = P.sincronizarConHorario(per0, cfg);
const by = (l, id) => l.find((p) => p.id === id);
ok(by(per, 'marivid').fijo === true && by(per, 'marivid').casa === 'Casa 3', 'primera vez no toca lo que ya estaba (Marivid sigue fija)');
ok(P.sincronizarConHorario(per, cfg) === per, 'sin cambios devuelve la misma lista');
cfg = { ...cfg, personal: [...cfg.personal, { id: 'rosa', n: 'Rosa', rol: 'aux', casas: ['Casa 3'], dias: [] }, { id: 'pedro', n: 'Pedro', rol: 'padre', casas: ['Casa 4'], dias: [] }] };

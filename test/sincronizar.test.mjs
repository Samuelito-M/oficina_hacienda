ok(!by(per, 'viviana').hasta, 'volver a poner en Horario la regresa');
cfg = { ...cfg, personal: cfg.personal.map((p) => (p.id === 'rosa' ? { ...p, rol: 'padre', casas: ['Casa 2'] } : p.id === 'pedro' ? { ...p, n: 'Pedro José' } : p)) };
per = P.sincronizarConHorario(per, cfg);
ok(by(per, 'rosa').fijo && by(per, 'rosa').casa === 'Casa 2', 'pasar a padre de casa en Horario la hace fija con su casa');
ok(by(per, 'pedro').nombre === 'Pedro José' && by(per, 'pedro').alias.includes('pedro'), 'cambiar el nombre conserva la forma anterior');
const manual = per.map((p) => (p.id === 'wendy' ? { ...p, hasta: '2026-11' } : p));
ok(P.sincronizarConHorario(manual, cfg) === manual, 'lo que se quita a mano en Acuerdos no lo deshace Horario');

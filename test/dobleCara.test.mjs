const avDic = auxConMuchosFindes(A.aAnalisis('2026-12', rDic.horario, cfg, personal), personal).map((m) => m.id).sort();
ok(JSON.stringify(avDic) === JSON.stringify(rDic.extras.map((x) => x.id).sort()), 'diciembre normal: el aviso muestra justo a quien la app le puso un 4.º fin de semana: ' + avDic.join(', '));

import fs from 'fs';
import JSZip from 'jszip';
const { DOMParser, XMLSerializer } = await import('@xmldom/xmldom');
globalThis.DOMParser = DOMParser;
globalThis.XMLSerializer = XMLSerializer;
const { leerWord, generarWord } = await import('../src/lib/acuerdos.js');
const { auxConMuchosFindes, acuerdosElegidos } = await import('../src/lib/seleccion.js');
const A = await import('../src/lib/horarioApp.js');
const P = await import('../src/lib/personal.js');
const ok = (c, m) => { console.log((c ? 'ok - ' : 'FALLA - ') + m); if (!c) process.exitCode = 1; };
const bytes = fs.readFileSync(process.argv[2]);
const w0 = await leerWord(bytes, JSZip);
const gente = w0.personas.slice(0, 4);
const cuantos = [3, 1, 2, 4];
const sab = [5, 12, 19, 26].map((d) => new Date(2026, 11, d));
const lista = [];
gente.forEach((p, i) => { for (let k = 0; k < cuantos[i]; k++) lista.push({ completo: p.completo, cedula: p.cedula, sabado: sab[k] }); });
lista.sort((a, b) => a.sabado - b.sabado);
const nombresEn = (xml) => {
  const texto = xml.replace(/<w:p[ >]/g, '\n<w:p ').replace(/<[^>]+>/g, '');
  return Array.from(texto.matchAll(/se(?:ñ|n)or\s*\(\s*a\s*\)\s*(.*?)\s*CC\.\s*(\d{10})/gi)).map((m) => m[2]);
};
const gen = async (porPersona, mantenerViejos = false) => {
  const w = await leerWord(bytes, JSZip);
  const out = await generarWord(w, lista, { mes: 11, anio: 2026, mantenerViejos, porPersona });
  return (await JSZip.loadAsync(out)).file('word/document.xml').async('string');
};
const xp = await gen(true);
const ced = nombresEn(xp);
const bloques = [];
for (const c of ced) if (!bloques.length || bloques[bloques.length - 1][0] !== c) bloques.push([c]); else bloques[bloques.length - 1].push(c);
ok(ced.length === 10 && bloques.length === 4, 'por persona: los 10 acuerdos quedan en 4 grupos seguidos (uno por persona)');
const ordenEsperado = gente.map((p, i) => ({ c: p.cedula, n: p.completo, k: cuantos[i] })).sort((a, b) => a.n.localeCompare(b.n, 'es'));
ok(JSON.stringify(bloques.map((b) => [b[0], b.length])) === JSON.stringify(ordenEsperado.map((x) => [x.c, x.k])), 'ordenados por nombre y con todos sus fines de semana');
const saltos = (xp.match(/<w:type w:val="oddPage"\/>/g) || []).length;
ok(saltos === 3, 'entre persona y persona hay un salto "a página impar" (3 saltos para 4 personas): ' + saltos);
ok((xp.match(/<w:sectPr/g) || []).length === 4, 'las secciones copian el formato de página del documento');
const fechas = Array.from(xp.replace(/<[^>]+>/g, '').matchAll(/S[aá]bado,?\s*(\d{1,2}) de diciembre/gi)).map((m) => +m[1]);
ok(fechas.length === 0 || fechas.length >= 10, 'fechas presentes');
const xs = await gen(false);
ok(!(xs.match(/oddPage/g) || []).length && nombresEn(xs).length === 10, 'con la casilla apagada queda como antes (sin saltos de sección)');
const xv = await gen(true, true);
ok(nombresEn(xv).length > 10 && (xv.match(/oddPage/g) || []).length >= 4, 'los acuerdos viejos que se conservan también van agrupados por persona');

const cfg = A.configInicial();
const cfgMuchos = A.normalizarConfig({ ...cfg, personal: cfg.personal.map((p) => (p.id === 'yazmira' ? { ...p, fm: A.TODOS_FINDES } : p)) });
const h = A.armar('2026-12', { dias: {}, vac: [], fer: [], notas: {}, obs: '' }, cfgMuchos, null).horario;
const personal = P.sincronizarConHorario(P.normalizarPersonal([]), cfgMuchos);
const an = A.aAnalisis('2026-12', h, cfgMuchos, personal);
const muchos = auxConMuchosFindes(an, personal);
const ctx = A.contexto('2026-12', h, cfgMuchos);
const yz = ctx.findes.filter((f) => f.dias.some((d) => ctx.donde('yazmira', d))).length;
ok(yz > 3 && muchos.some((m) => m.id === 'yazmira' && m.findes.length === yz), `Yazmira (todos los fines de semana: ${yz}) sale en el aviso`);
ok(muchos.every((m) => m.findes.length > 3), 'solo salen quienes pasan de 3');
let h2 = h;
for (const f of ctx.findes) for (const d of f.dias) if (!A.en(h2, d, 'Casa 1').includes('miguel')) h2 = A.poner(h2, d, 'Casa 1', [...A.en(h2, d, 'Casa 1'), 'miguel']);
const an2 = A.aAnalisis('2026-12', h2, cfgMuchos, personal);
ok(!auxConMuchosFindes(an2, personal).some((m) => m.id === 'miguel'), 'los padres de casa no salen en el aviso aunque trabajen todos los fines de semana');
